import 'package:youtube_explode_dart/youtube_explode_dart.dart';

void main() async {
  final yt = YoutubeExplode();
  try {
    final videoId = 'dQw4w9WgXcQ';
    final manifest = await yt.videos.closedCaptions.getManifest(videoId);
    print('Tracks count: ${manifest.tracks.length}');
    for (final t in manifest.tracks) {
      print('Track: ${t.language.name} (${t.language.code}), auto-generated: ${t.isAutoGenerated}');
    }
    if (manifest.tracks.isNotEmpty) {
      final track = await yt.videos.closedCaptions.get(manifest.tracks.first);
      print('Captions count: ${track.captions.length}');
      for (final c in track.captions.take(5)) {
        print('At ${c.offset.inSeconds}s (${c.duration.inSeconds}s): ${c.text}');
      }
    }
  } catch (e) {
    print('Error: $e');
  } finally {
    yt.close();
  }
}
